#!/usr/bin/env python3
"""vod_router：Hermes shell hook（pre_llm_call）——确定性意图路由。

统一架构（D-hook-unify-1）：路由不再做成 hermes 插件包（要 plugins.enabled、要
宿主进程内 import），而是一个**与宿主无关的钩子脚本**：stdin 读 JSON 事件载荷，
stdout 输出 {"context": "..."}；由各宿主自己的机制注册（hermes=`config.yaml` 的
hooks.pre_llm_call，子进程隔离、按 (event, command) 首次同意）。线协议见
hermes docs「Shell Hooks → JSON wire protocol」。

判定顺序（单一判定路径，route_detail 逐层自述 reason）：
1. `empty`            —— 非字符串/空文本，什么都不做；
2. `envelope`         —— 宿主信封（内部通知/后台回执/压缩摘要）先剥掉；剥完若没有
                         「用户在说话」的标记就不判（S212/S219）；
3. `strong-prefix`    —— 显式「提交反馈：」前缀直接注入，不被任何排除规则压掉；
4. `no-trigger`       —— 触发词（TRIGGER_WORDS）与失能词（DISABLE_WORDS）都没命中；
5. `engineering-object` —— 只有失能词 + 工程对象（配置文件/字段/缓存…）+ 无用户锚点
                         → 工程师在说自己的代码（S218）；
6. `meta-discussion`  —— 工程语汇命中且无用户视角锚点 → 元讨论（S185/S202）；
7. `trigger` / `disable` —— 命中即注入；`disable` 标记「靠失能词而不是现象词命中」（S211）

规则表纪律：新增触发词改 TRIGGER_WORDS（单一事实源），改文案改 DIRECTIVE /
STRONG_DIRECTIVE，改元讨论排除改 META_WORDS / ANCHOR_WORDS；三处都有回归锁
（tests/test_router.py 的 S185/S186 与 R7）。
"""
import json
import re
import sys

TRIGGER_WORDS = (
    "提交反馈", "提单",
    "体验不好", "体验差", "体验很差", "体验糟", "很糟糕", "太糟糕",
    "体验太差", "太差", "很差",
    "太慢", "很慢", "回复慢", "响应慢",
    "卡顿", "卡死", "卡",
    "白屏", "没反应",
    "登录不上", "登录不了", "登不上",
    "不好用", "很难用", "太麻烦", "很麻烦", "麻烦死了", "不方便",
    "报错", "有bug", "有 bug", "出bug",
    # S184 现象词同表（S193）：教模型的分型词与路由判据必须是同一份，别造两份真源
    "失败", "打不开", "超时", "崩",
    "希望支持", "建议增加", "要是能", "为什么不能",
)

# 裸「卡」必须带边界（S193）：卡片/卡号/卡券/卡通/卡位/卡口/卡车/车牌 不是抱怨。
# 词表仍只写「卡」一个字（单一事实源），边界在装配正则时加——这样新增触发词不必
# 记着两条规则。
_KA_GUARD = r"卡(?!片|号|券|通|位|口|车|牌|包|针)"

# S185 元讨论排除（D-router-scope-1）：命中词出现在「谈工程对象」的句子里时，
# 用户谈的是产品反馈这件事（评审/方案/代码/文档），不是他自己的遭遇。实测 7 条
# 元讨论 6 条被误判成采集意图，注入指令会把设计评审拐去提单。
# 判据 = 命中 META_WORDS 且不含任何「用户视角对象/体验面」锚点 → 零注入。
# 为什么不用模型判断：本 hook 是确定性路由（线协议只回 context，不跑 LLM），
# 且误注入比漏注入贵——漏了模型仍可能自识别反馈，误注入会打断当前任务。
META_WORDS = (
    # 纯工程产物/工位语汇：用户不会用这些词说自己的体验
    "代码", "用例", "测试", "门禁", "文档", "ADR", "断言", "夹具",
    "PR", "MR", "评审", "方案", "仓库", "分支", "发版", "部署",
    "脚本", "函数", "模块", "依赖", "tag", "commit", "pytest", "mypy",
    "profile", "packs", "载荷", "适配器", "巡检", "账本", "契约", "需求",
    # 工程动作词才是「元讨论」的真信号（S193）：接口/配置/字段/日志/版本 是共用词，不在此列
    "改成", "抽成", "重构", "实现", "写死", "解耦", "排查", "调一下", "补一",
    # 工程第二层（S195）：CI/构建/编译/流水线/发布/回滚/单测/环境/栈 是工程语境，
    # 用户说自己的体验不会用这些词（「构建失败」是开发者在说自己的流水线）
    "CI", "构建", "编译", "流水线", "回滚", "单测", "栈",
    # S202：只收**工程搭配**，不收裸「发布」「环境」——用户也会说"刚发布的版本打不开"
    # "生产环境卡死了"（上一轮收裸词直接压掉了用户视角，与 hermes-router.md 的口径矛盾）
    "发布流水线", "发布流程", "环境变量", "测试环境", "预发环境", "构建产物",
)
ANCHOR_WORDS = (
    "产品", "平台", "网站", "网页", "页面", "界面", "客户端", "插件", "工具", "系统",
    "功能", "按钮", "菜单", "搜索框", "输入框", "登录", "上传", "下载", "导出",
    "加载", "速度", "打开", "点击", "点了", "体验",
)
# S211：第二条判定路径——失能/否定词。词表路线（TRIGGER）只能覆盖"我们想得到的说法"；
# 用户常用的是「挂了/用不了/闪退/丢了/空的/没动静/转圈/不回/难用/自动刷新」这类**失能描述**，
# 它们几乎不出现在工程语境里（工程师说"排查/重构/构建失败"）。命中即进入采集意图，
# 工程搭配仍由 META 优先排除（META 且无 ANCHOR → 零注入）。
DISABLE_WORDS = (
    "用不了", "没法用", "不能用", "挂了", "闪退", "丢了", "没了", "空的", "没动静",
    "不相关", "太难用", "难用", "不回", "转圈", "自动刷新",
)

# S218：工程对象词。失能词路径（S211）如果不排除工程对象，「配置文件丢了」「这个字段是空的」
# 「日志是空的」「缓存丢了」这类工程师自述会被当成用户抱怨——用户视角优先仍然成立：
# 命中 ANCHOR（页面/按钮/导出…）就不排除。
ENGINE_OBJ_WORDS = (
    "配置文件", "配置项", "字段", "数据集", "缓存", "模板", "日志", "索引",
    "库表", "数据库", "表结构", "服务", "进程", "脚本", "证书", "密钥", "集群",
)

# S212：网关/框架信封不是用户原话。内部通知、后台进程回执、压缩摘要、prior context 里
# 天然含「失败/改写/工具数」这类词，注入只会污染当轮上下文（实测连续多次）。
# 注意：`[OUT-OF-BAND USER MESSAGE …]` 是**用户本人**的消息包装，不在本表——里面照旧判定。
ENVELOPE_MARKERS = (
    "【内部通知】", "【系统通知】", "【后台任务】",
    "[INTERNAL NOTIFICATION",
    "[IMPORTANT: Background process",
    "[PRIOR CONTEXT",
    "[CONTEXT COMPACTION",
    "generated by the Hermes gateway",
)

# S223：判据的"结论标签"在这里一次声明——用例断言实际产出的标签集与之相等，
# 且每个标签都必须在 docs/design.md 登记（文档与判据同步的门禁）。
REASONS = ("empty", "envelope", "strong-prefix", "no-trigger",
           "engineering-object", "meta-discussion", "trigger", "disable")

_STRONG_PREFIX = "提交反馈"

def _trigger_pattern(words=TRIGGER_WORDS) -> str:
    """装配触发词正则（单一事实源）：除裸「卡」外逐词 re.escape。"""
    return "|".join(_KA_GUARD if w == "卡" else re.escape(w) for w in words)


_COMPLAINT_RE = re.compile(_trigger_pattern())
_META_RE = re.compile("|".join(re.escape(w) for w in META_WORDS))
_ANCHOR_RE = re.compile("|".join(re.escape(w) for w in ANCHOR_WORDS))
_DISABLE_RE = re.compile("|".join(re.escape(w) for w in DISABLE_WORDS))
_ENG_OBJ_RE = re.compile("|".join(re.escape(w) for w in ENGINE_OBJ_WORDS))

# S219：信封要"剥掉再判"，不能"含标记就整条判死"——否则信封后面跟的用户显式指令
# 会被一起吞掉（实测 3/3）。剥完的余文里若出现"用户在说话"的标记，继续走正常判定。
_USER_INTENT_RE = re.compile("提交反馈|帮我|我要|我这边|我们|麻烦你|你们家|我试|我点|我觉得")


def _strip_envelopes(text: str) -> str:
    """去掉信封标记行及其载荷行，返回可能的用户余文。"""
    out = []
    skipping = False
    for line in text.splitlines():
        hit = next((m for m in ENVELOPE_MARKERS if m in line), None)
        if hit:
            skipping = True
            continue
        if skipping and (line.lstrip().startswith("[") or not line.strip()):
            continue
        skipping = False
        out.append(line)
    return "\n".join(out).strip()

DIRECTIVE = (
    "[vod-router] 确定性意图路由命中：本消息匹配产品反馈采集意图（规则命中，非模型判断）。"
    "必须按 vod-feedback-collect 技能流程处理：先承接用户，再征得提交同意"
    "（产品未定时必须问一次『这条是哪个产品的反馈』，不许裸提交；"
    "用户说不知道就不提交（缺产品不提交）；禁止进入复现排查模式）。"
    "提交时 content=用户原话逐字，一次抱怨一条，回执按 echo 原样转述。"
)

STRONG_DIRECTIVE = (
    "[vod-router] 显式反馈指令（「提交反馈」前缀，确定性短路）：必须立即按 "
    "vod-feedback-collect 技能流程执行采集，无需再判断意图。"
)


def _text_of(payload: dict) -> str:
    """取这一轮的用户原话：real payload 把 user_message 放在 extra 里；
    user_message 可能是多模态列表（取其中的 text 段）。"""
    extra = payload.get("extra") or {}
    msg = extra.get("user_message", payload.get("user_message"))
    if isinstance(msg, list):
        parts = []
        for part in msg:
            if isinstance(part, dict):
                if part.get("type") in (None, "text") and part.get("text"):
                    parts.append(str(part["text"]))
            elif isinstance(part, str):
                parts.append(part)
        msg = "\n".join(parts)
    return msg if isinstance(msg, str) else ""


def route_detail(text) -> dict:
    """判定可解释（S203）：把三层各自的结论说出来，供用例与排障使用。

    四轮词表问题（S185→S193→S195→S202）都是「某条真实原话被判到另一侧」，而每次只能
    靠人工逐句跑探针才看出是哪一层压掉的。这里把结论结构化：
    decision = strong | inject | silent；reason = strong-prefix | trigger |
    no-trigger | meta-discussion | empty；trigger/meta 给出命中的词。
    route() 是它的薄包装——**单一判定路径**，别让两层各算一次。
    """
    base = {"decision": "silent", "reason": "", "trigger": None, "meta": None,
            "directive": None}
    if not isinstance(text, str) or not text.strip():
        return {**base, "reason": "empty"}
    if any(marker in text for marker in ENVELOPE_MARKERS):
        rest = _strip_envelopes(text)
        if not rest or not _USER_INTENT_RE.search(rest):
            return {**base, "reason": "envelope"}
        text = rest      # 剥完还有用户在说话 → 按正常判定
    if text.lstrip().startswith(_STRONG_PREFIX):
        return {**base, "decision": "strong", "reason": "strong-prefix",
                "directive": STRONG_DIRECTIVE}
    m = _COMPLAINT_RE.search(text)
    d = _DISABLE_RE.search(text)
    if not m and not d:
        return {**base, "reason": "no-trigger"}
    hit = (m or d).group(0)
    # S218：纯失能词（无强抱怨触发词）+ 工程对象 + 无用户视角锚点 → 工程师在说代码
    if d and not m and _ENG_OBJ_RE.search(text) and not _ANCHOR_RE.search(text):
        return {**base, "reason": "engineering-object", "trigger": hit,
                "meta": _ENG_OBJ_RE.search(text).group(0)}
    meta = _META_RE.search(text)
    if meta and not _ANCHOR_RE.search(text):
        return {**base, "reason": "meta-discussion", "trigger": hit,
                "meta": meta.group(0)}
    return {**base, "decision": "inject", "reason": "trigger" if m else "disable",
            "trigger": hit, "directive": DIRECTIVE}


def route(text) -> str | None:
    """返回要注入的指令；未命中/非字符串返回 None（钩子绝不对载荷形状抛错）。"""
    return route_detail(text)["directive"]


def main() -> int:
    try:
        raw = sys.stdin.read()
        payload = json.loads(raw) if raw.strip() else {}
    except (json.JSONDecodeError, OSError):
        return 0          # 载荷不可解析=不注入，绝不打断宿主这一轮
    directive = route(_text_of(payload))
    if directive:
        # 协议：dict 里 "context" 键的文本被追加到本轮用户消息
        sys.stdout.write(json.dumps({"context": directive}, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    sys.exit(main())